"""Tests for the Markdown audit report."""

from __future__ import annotations

import unittest
from datetime import date

from three_step_audit.evidence import EvidenceItem, EvidencePlan
from three_step_audit.findings import Conclusion, Finding, FindingRegister
from three_step_audit.models import AuditScope
from three_step_audit.report import render_markdown
from three_step_audit.workflow import Workflow

GENERATED = date(2026, 10, 26)


def sample_scope() -> AuditScope:
    return AuditScope(
        title="FY26 access-control review",
        organization="Northwind Logistics",
        audit_type="Internal",
        standard="ISO 27001",
        period_start=date(2026, 1, 1),
        period_end=date(2026, 6, 30),
        lead_auditor="R. Parslow",
        scope_summary="Review quarterly access reviews for all production systems.",
        in_scope_areas=["Access control", "Change management"],
        objectives=["Confirm access reviews happen quarterly"],
        exclusions="Vendor-managed systems",
    )


def sample_evidence() -> EvidencePlan:
    return EvidencePlan(
        methodology="Sampled every production system and re-performed one review.",
        items=[
            EvidenceItem(
                reference="AC-01",
                description="Quarterly access review completed | signed off by the CISO.",
                source="Identity team",
                objective="Confirm access reviews happen quarterly",
                collected_on=date(2026, 10, 1),
                result="Pass",
                notes="No gaps | no exceptions",
            )
        ],
    )


def sample_register() -> FindingRegister:
    return FindingRegister(
        findings=[
            Finding(
                reference="F-01",
                title="Review log missing for one system",
                severity="Medium",
                objective="Confirm access reviews happen quarterly",
                evidence_reference="AC-01",
                condition="One of twelve systems had no review log for Q2.",
                recommendation="Add the missing system to the quarterly review calendar.",
                owner="R. Parslow",
                due_on=date(2026, 12, 1),
                status="Open",
            )
        ],
        conclusion=Conclusion(
            opinion="Conforms with exceptions",
            summary="Reviews run as designed, with one documentation gap recorded as a finding.",
            concluded_by="R. Parslow",
            concluded_on=date(2026, 10, 20),
        ),
    )


class CompleteReportTests(unittest.TestCase):
    def setUp(self) -> None:
        self.report = render_markdown(
            Workflow(
                scope=sample_scope(),
                evidence=sample_evidence(),
                findings=sample_register(),
            ),
            generated_on=GENERATED,
        )

    def test_heading_and_engagement_details(self) -> None:
        self.assertIn("# FY26 access-control review", self.report)
        self.assertIn("**Organization:** Northwind Logistics", self.report)
        self.assertIn("**Criteria:** ISO 27001", self.report)
        self.assertIn("01 Jan 2026 – 30 Jun 2026", self.report)
        self.assertIn("**Exclusions:** Vendor-managed systems", self.report)

    def test_sections_appear_in_order(self) -> None:
        order = [
            "## Scope",
            "## Objectives",
            "## Evidence & testing",
            "## Findings",
            "## Conclusion",
        ]
        positions = [self.report.index(section) for section in order]
        self.assertEqual(positions, sorted(positions))

    def test_evidence_table_and_detail_lines(self) -> None:
        self.assertIn("| Ref | Objective | Source | Collected | Result |", self.report)
        self.assertIn("| AC-01 | Confirm access reviews happen quarterly |", self.report)
        self.assertIn("| Identity team | 2026-10-01 | Pass |", self.report)
        self.assertIn(r"- **AC-01** — Quarterly access review completed \| signed off", self.report)
        self.assertIn(r"_Notes: No gaps \| no exceptions_", self.report)

    def test_findings_and_conclusion(self) -> None:
        self.assertIn("### F-01 — Review log missing for one system", self.report)
        self.assertIn("- **Severity:** Medium", self.report)
        self.assertIn("- **Due:** 2026-12-01", self.report)
        self.assertIn("**Recommendation:** Add the missing system", self.report)
        self.assertIn("**Opinion:** Conforms with exceptions", self.report)
        self.assertIn("Concluded by R. Parslow on 2026-10-20.", self.report)

    def test_generation_note_is_deterministic(self) -> None:
        self.assertIn("_Generated by ThreeStepAudit on 2026-10-26._", self.report)


class PartialReportTests(unittest.TestCase):
    def test_scope_only_report_marks_the_later_steps_as_pending(self) -> None:
        report = render_markdown(Workflow(scope=sample_scope()), generated_on=GENERATED)
        self.assertIn("_Not recorded yet._", report)
        self.assertIn("_No findings recorded._", report)
        self.assertIn("_Not concluded yet._", report)

    def test_scope_and_evidence_report_has_no_conclusion(self) -> None:
        report = render_markdown(
            Workflow(scope=sample_scope(), evidence=sample_evidence()),
            generated_on=GENERATED,
        )
        self.assertIn("| AC-01 |", report)
        self.assertIn("_No findings recorded._", report)

    def test_report_requires_a_scope(self) -> None:
        with self.assertRaises(ValueError):
            render_markdown(Workflow())


if __name__ == "__main__":
    unittest.main()
