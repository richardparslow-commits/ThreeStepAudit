"""Render a saved audit as a Markdown report."""

from __future__ import annotations

from datetime import date

from three_step_audit.workflow import Workflow


def render_markdown(workflow: Workflow, generated_on: date | None = None) -> str:
    """Return the audit as Markdown: readable in a PR, a ticket, or a PDF export."""
    scope = workflow.scope
    if scope is None:
        raise ValueError("there is no scope to report on yet")

    generated_on = generated_on or date.today()
    lines: list[str] = [f"# {scope.title.strip() or 'Untitled audit'}", ""]

    lines += [
        f"- **Organization:** {scope.organization.strip()}",
        f"- **Audit type:** {scope.audit_type}",
        f"- **Criteria:** {scope.criteria()}",
        f"- **Period under review:** {scope.period_label()}",
        f"- **Lead auditor:** {scope.lead_auditor.strip()}",
        "",
        "## Scope",
        "",
        scope.scope_summary.strip(),
        "",
        f"**In scope:** {', '.join(scope.in_scope_areas) or 'none recorded'}",
    ]
    if scope.exclusions.strip():
        lines += ["", f"**Exclusions:** {scope.exclusions.strip()}"]
    lines += ["", "## Objectives", ""]
    if scope.objectives:
        lines += [f"{number}. {objective}" for number, objective in enumerate(scope.objectives, 1)]
    else:
        lines.append("_No objectives recorded._")

    evidence = workflow.evidence
    lines += ["", "## Evidence & testing", ""]
    if evidence is None:
        lines.append("_Not recorded yet._")
    else:
        lines += [evidence.methodology.strip(), ""]
        if evidence.items:
            lines += [
                "| Ref | Objective | Source | Collected | Result |",
                "| --- | --- | --- | --- | --- |",
            ]
            for item in evidence.items:
                lines.append(
                    "| "
                    + " | ".join(
                        _cell(value)
                        for value in (
                            item.reference,
                            item.objective,
                            item.source,
                            item.collected_on.isoformat() if item.collected_on else "",
                            item.result,
                        )
                    )
                    + " |"
                )
            lines.append("")
            for item in evidence.items:
                lines.append(f"- **{_cell(item.reference) or 'evidence'}** — {_cell(item.description)}")
                if item.notes.strip():
                    lines.append(f"  - _Notes: {_cell(item.notes)}_")
        else:
            lines.append("_No evidence recorded._")

    register = workflow.findings
    lines += ["", "## Findings", ""]
    if register is None or not register.findings:
        lines.append("_No findings recorded._")
    else:
        for finding in register.findings:
            lines += [
                f"### {finding.reference.strip() or 'Finding'} — "
                f"{finding.title.strip() or 'untitled'}",
                "",
                f"- **Severity:** {finding.severity}",
                f"- **Status:** {finding.status}",
                f"- **Owner:** {finding.owner.strip()}",
                f"- **Due:** {finding.due_on.isoformat() if finding.due_on else 'not set'}",
                f"- **Objective:** {finding.objective}",
                f"- **Evidence:** {finding.evidence_reference or 'not linked'}",
                "",
                finding.condition.strip(),
                "",
                f"**Recommendation:** {finding.recommendation.strip()}",
                "",
            ]

    lines += ["", "## Conclusion", ""]
    if register is None:
        lines.append("_Not concluded yet._")
    else:
        conclusion = register.conclusion
        lines += [f"**Opinion:** {conclusion.opinion}", "", conclusion.summary.strip()]
        if conclusion.concluded_on:
            lines += [
                "",
                f"Concluded by {conclusion.concluded_by.strip() or 'unattributed'} on "
                f"{conclusion.concluded_on.isoformat()}.",
            ]

    lines += ["", "---", f"_Generated by ThreeStepAudit on {generated_on.isoformat()}._", ""]
    return "\n".join(lines)


def _cell(value: str) -> str:
    """Keep one value inside one Markdown table cell."""
    return " ".join(value.strip().split()).replace("|", "\\|")
